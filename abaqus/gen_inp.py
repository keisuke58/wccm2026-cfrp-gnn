           " 3, 0.0",
           "*SOLID SECTION, ELSET=EALL, MATERIAL=CFRTP, ORIENTATION=ORI0",
           "**",
           "*MATERIAL, NAME=CFRTP",
           "*DEPVAR",
           " 3,",
           "1, alpha, degree of cure",
           "2, g_chile, stiffness fraction",
           "3, smax, max abs sigma11",
