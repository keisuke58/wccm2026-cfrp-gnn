           "*STEP, NLGEOM=NO, INC=500",
           "*STATIC",
           " 0.005, 1.0, 1.0e-6, 0.02",
           "*TEMPERATURE, AMPLITUDE=CURECYCLE",
           " NALL, 1.0",
           "*OUTPUT, FIELD",
           "*ELEMENT OUTPUT",
           " S, E, SDV",
