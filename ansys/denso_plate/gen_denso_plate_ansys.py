"""ansys/denso_plate/gen_denso_plate_ansys.py -- the Denso residual-strain plate of
abaqus/denso_plate/gen_denso_plate.py, written as an Ansys Mechanical APDL batch input, so that
the same lamination check can be run in Ansys (the solver Denso uses).

Same model as the Abaqus deck, node for node and element for element:
  * quarter of a free 100 mm x 100 mm x 3 mm plate (symmetry planes x = 0, y = 0), 25 x 25 in
    plane, 40 element layers; SOLID185 with KEYOPT(2) = 3 (simplified enhanced strain, i.e.
    incompatible bending modes -- the counterpart of Abaqus C3D8I);
  * one orthotropic material per layer (MP,EX..GXZ from the orientation-averaged <C>; global
    axes, so no ESYS is needed), eigenstrain imposed as secant expansion ALPX/ALPY/ALPZ =
    e*/dT with TREF = T_lock and a uniform temperature T_room (BFUNIF);
  * output: elastic strain EPEL X, Y of the centre-column elements (ETABLE = average of the
    element nodal values, the centroid value for this linear-in-z field) and UZ of the
    mid-plane nodes on both symmetry axes, written to CSV files by *VWRITE.
The reference (<job>_ref.json) is the exact piecewise-constant lamination solution of
gen_denso_plate.py, and abaqus/denso_plate/compare_denso_plate.py --ansys checks the result.

Validated here (no Ansys in this environment):
  A1 the MP constants rebuild the layer stiffness <C> to machine precision (the same
     engineering-constant definition -- major Poisson ratios PRXY, PRYZ, PRXZ -- as the
     Abaqus UMAT, whose stiffness was checked against lamination theory to 1.8e-15);
  A2 the comparison path (CSV reader -> compare_denso_plate) on CSVs written from the reference.
NOT validated: the APDL input has not been run in Ansys. Run it, check it, report failures as
they are (research/GUIDE_ansys.md).

Honest scope: identical to gen_denso_plate.py (linear elastic eigenstrain model; constants
ILLUSTRATIVE; orientation profile assumed). The process analysis (heat transfer +
crystallisation-coupled viscoelastic UMAT) has NO Ansys counterpart yet: it needs the UMAT
ported to Ansys USERMAT.

Usage:  python3 ansys/denso_plate/gen_denso_plate_ansys.py [--part thermal|cryst] [--sample N]
Inputs go to ansys/denso_plate/jobs/ (gitignored).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "abaqus", "denso_plate"))
import gen_denso_plate as gp  # noqa: E402
from denso_plate_features import orientation_profile, CASES  # noqa: E402
ml = gp.ml

NX, NY, NL = gp.NX, gp.NY, gp.NL
nid, eid = gp.nid, gp.eid


def eng_constants(Cv):
    """Repo Voigt stiffness (11,22,33,23,13,12, engineering shear) -> Ansys orthotropic MP set."""
    S = np.linalg.inv(Cv)
    EX, EY, EZ = 1 / S[0, 0], 1 / S[1, 1], 1 / S[2, 2]
    return dict(EX=EX, EY=EY, EZ=EZ, PRXY=-S[0, 1] * EX, PRYZ=-S[1, 2] * EY, PRXZ=-S[0, 2] * EX,
                GXY=1 / S[5, 5], GYZ=1 / S[3, 3], GXZ=1 / S[4, 4])


def rebuild(mp):
    """Stiffness from the MP set, in repo Voigt order (check A1)."""
    S = np.zeros((6, 6))
    S[0, 0], S[1, 1], S[2, 2] = 1 / mp["EX"], 1 / mp["EY"], 1 / mp["EZ"]
    S[0, 1] = S[1, 0] = -mp["PRXY"] / mp["EX"]
    S[1, 2] = S[2, 1] = -mp["PRYZ"] / mp["EY"]
    S[0, 2] = S[2, 0] = -mp["PRXZ"] / mp["EX"]
    S[3, 3], S[4, 4], S[5, 5] = 1 / mp["GYZ"], 1 / mp["GXZ"], 1 / mp["GXY"]
    return np.linalg.inv(S)


def write_apdl(path, job, title, lay, c):
    H = c.H; a = gp.L_PLATE / 2
    xs = np.linspace(0, a, NX + 1); ys = np.linspace(0, a, NY + 1); zs = np.linspace(-H / 2, H / 2, NL + 1)
    L = ["/BATCH", f"/TITLE,Denso residual-strain plate ({title})",
         "! Generated by ansys/denso_plate/gen_denso_plate_ansys.py. ILLUSTRATIVE constants.",
         "! Units: m, Pa, deg C. Same mesh and numbering as abaqus/denso_plate/gen_denso_plate.py.",
         "/PREP7", "ET,1,SOLID185", "KEYOPT,1,2,3            ! simplified enhanced strain (~ C3D8I)"]
    for k in range(NL + 1):
        for j in range(NY + 1):
            for i in range(NX + 1):
                L.append(f"N,{nid(i, j, k)},{xs[i]:.9e},{ys[j]:.9e},{zs[k]:.9e}")
    err = 0.0
    for k in range(NL):
        mp = eng_constants(lay["C"][k])
        err = max(err, float(np.max(np.abs(rebuild(mp) - lay["C"][k])) / np.max(np.abs(lay["C"][k]))))
        ae = lay["estar"][k] / lay["dT"]
        m = k + 1
        L.append(f"! layer {m}: z/(H/2) = {lay['zm'][k]:+.4f}, a11 {lay['a11'][k]:.4f}, "
                 f"a22 {lay['a22'][k]:.4f}, a33 {lay['a33'][k]:.4f}, X_c {lay['Xc'][k]:.4f}")
        for key in ("EX", "EY", "EZ", "PRXY", "PRYZ", "PRXZ", "GXY", "GYZ", "GXZ"):
            L.append(f"MP,{key},{m},{mp[key]:.10e}")
        for key, v in zip(("ALPX", "ALPY", "ALPZ"), ae):
            L.append(f"MP,{key},{m},{v:.10e}")
    L.append("TYPE,1")
    for k in range(NL):
        L.append(f"MAT,{k+1}")
        for j in range(NY):
            for i in range(NX):
                n = [nid(i, j, k), nid(i + 1, j, k), nid(i + 1, j + 1, k), nid(i, j + 1, k),
                     nid(i, j, k + 1), nid(i + 1, j, k + 1), nid(i + 1, j + 1, k + 1), nid(i, j + 1, k + 1)]
                L.append(f"EN,{eid(i, j, k)}," + ",".join(map(str, n)))
    L += ["! boundary conditions: symmetry planes and one point against rigid-body z",
          "NSEL,S,LOC,X,0", "D,ALL,UX,0", "NSEL,S,LOC,Y,0", "D,ALL,UY,0",
          f"NSEL,S,NODE,,{nid(0, 0, 0)}", "D,ALL,UZ,0", "ALLSEL,ALL", "FINISH",
          "/SOLU", "ANTYPE,STATIC", f"TREF,{c.T_LOCK:.4f}", f"BFUNIF,TEMP,{c.T_ROOM:.4f}",
          "SOLVE", "FINISH", "/POST1", "SET,LAST", "ETABLE,EPX,EPEL,X", "ETABLE,EPY,EPEL,Y"]
    col = [eid(0, 0, k) for k in range(NL)]
    midx = [nid(i, 0, NL // 2) for i in range(NX + 1)]
    midy = [nid(0, j, NL // 2) for j in range(NY + 1)]

    def arr(name, vals):
        out = [f"*DIM,{name},ARRAY,{len(vals)}"]
        out += [f"{name}({i+1})={v}" for i, v in enumerate(vals)]
        return out
    L += arr("ECOL", col) + [f"*DIM,EXX,ARRAY,{NL}", f"*DIM,EYY,ARRAY,{NL}",
                              f"*DO,II,1,{NL}", "*GET,EXX(II),ELEM,ECOL(II),ETAB,EPX",
                              "*GET,EYY(II),ELEM,ECOL(II),ETAB,EPY", "*ENDDO",
                              f"*CFOPEN,{job}_ansys_col,csv", "*VWRITE,ECOL(1),EXX(1),EYY(1)",
                              "(F10.0,',',E24.15,',',E24.15)", "*CFCLOS"]
    for nm, lab in (("MIDX", midx), ("MIDY", midy)):
        L += arr("N" + nm, lab) + [f"*DIM,U{nm},ARRAY,{len(lab)}", f"*DO,II,1,{len(lab)}",
                                   f"*GET,U{nm}(II),NODE,N{nm}(II),U,Z", "*ENDDO",
                                   f"*CFOPEN,{job}_ansys_{nm.lower()},csv",
                                   f"*VWRITE,N{nm}(1),U{nm}(1)", "(F10.0,',',E24.15)", "*CFCLOS"]
    L += ["FINISH"]
    open(path, "w").write("\n".join(L) + "\n")
    return dict(col_elements=col, midx_nodes=midx, midy_nodes=midy, x_mid=xs.tolist(),
                y_mid=ys.tolist()), err


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--part", default="total", choices=["total", "thermal", "cryst"])
    ap.add_argument("--sample", type=int, default=0)
    ap.add_argument("--seed", type=int, default=ml.SEED)
    ap.add_argument("--out", default=os.path.join(HERE, "jobs"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    c = ml.SOURCE
    jobs = []
    if a.sample:
        rng = np.random.default_rng(a.seed)
        for n, (Tb, Tt, op) in enumerate(ml.sample_params(rng, a.sample)):
            jobs.append((f"denso_sample_{n:04d}", f"sample {n}, mould {Tb:.1f}/{Tt:.1f} C",
                         (lambda z, op=op: ml.orientation(z, op)), Tb, Tt))
    else:
        for name, (Tb, Tt) in CASES.items():
            sfx = "" if a.part == "total" else "_" + a.part
            jobs.append((f"denso_{name}{sfx}", f"{name}, mould {Tb:.0f}/{Tt:.0f} C, {a.part}",
                         orientation_profile, Tb, Tt))
    manifest = []
    for job, title, ofn, Tb, Tt in jobs:
        lay = gp.layer_data(ofn, ml.crystallise(Tb, Tt, c), c, a.part)
        ref = gp.lamination_pc(lay["zm"], lay["C"], lay["estar"], c.H)
        info, err = write_apdl(os.path.join(a.out, job + ".dat"), job, title, lay, c)
        out = dict(job=job, title=title, part=a.part, NL=NL, NX=NX, NY=NY, L_plate=gp.L_PLATE, H=c.H,
                   T_lock=c.T_LOCK, T_room=c.T_ROOM, zm=lay["zm"].tolist(), Xc=lay["Xc"].tolist(),
                   ref_exx=ref["em"][:, 0].tolist(), ref_eyy=ref["em"][:, 1].tolist(),
                   ref_e0=ref["e0"].tolist(), ref_kappa=ref["kappa"].tolist(), T_bottom=Tb, T_top=Tt,
                   mp_rebuild_err=err, **info)
        with open(os.path.join(a.out, job + "_ref.json"), "w") as f:
            json.dump(out, f, separators=(",", ":"))
        print(f"{job:28s} A1 MP -> <C> rebuild {err:.1e} | sag_y {ref['kappa'][1]*gp.L_PLATE**2/8*1e3:+.4f} mm")
        assert err < 1e-12, "MP constants do not reproduce the layer stiffness"
        manifest.append(job)
    open(os.path.join(a.out, "manifest.txt"), "w").write("\n".join(manifest) + "\n")
    print(f"wrote {len(manifest)} APDL input(s) + references to {a.out}")


if __name__ == "__main__":
    main()
