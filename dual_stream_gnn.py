def _parse() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Dual-stream raw+diff GNN experiment")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--train",       action="store_true")
    mode.add_argument("--eval",        action="store_true")
    mode.add_argument("--test",        action="store_true")

    ap.add_argument("--arch",         default="hybridmgn",
                    choices=["hybridmgn", "meshgraphnet", "gat", "sage"])
    ap.add_argument("--epochs",       type=int,   default=200)
    ap.add_argument("--batch_size",   type=int,   default=32)
    ap.add_argument("--lr",           type=float, default=1e-3)
    ap.add_argument("--eval_every",   type=int,   default=10)
    ap.add_argument("--noise_std",           type=float, default=0.05,
                    help="Noise on both channels of defective specimens")
    ap.add_argument("--noise_healthy_std",   type=float, default=0.03,
                    help="Extra noise on raw channel of healthy nodes (Stage-0 robustness)")
    ap.add_argument("--baseline_noise_std",  type=float, default=0.02,
                    help="Perturbation to diff channel simulating imperfect baseline")
    ap.add_argument("--diff_channel_dropout", type=float, default=0.15,
                    help="Prob of zeroing diff channel per specimen (no-baseline robustness)")
    ap.add_argument("--ckpt",                default=None,
                    help="Checkpoint path for --eval mode")
    ap.add_argument("--no_baseline",  action="store_true",
                    help="Zero the diff channel at eval (simulate no-baseline scenario)")
    return ap.parse_args()


if __name__ == "__main__":
    args = _parse()
    if args.test:
        _tests()
    elif args.train:
        train_dual(args)
    elif args.eval:
        if args.ckpt is None:
            args.ckpt = str(CK_OUT / f"{args.arch}_dual_best.pth")
        eval_dual(args)
