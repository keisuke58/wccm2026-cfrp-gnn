def _tests() -> None:
    print("[test] Checking dual_stream_gnn imports and data shape logic...")

    # Synthetic node feature check: 5 channels
    N = 13942
    cx = np.random.randn(N).astype(np.float32)
    cy = np.random.randn(N).astype(np.float32)
    cz = np.random.randn(N).astype(np.float32)
    diff = np.random.randn(N).astype(np.float32)
    raw  = np.random.randn(N).astype(np.float32)

    feats = np.column_stack([cx, cy, cz, diff, raw])
    assert feats.shape == (N, 5), f"Expected (N,5), got {feats.shape}"

    # no_baseline mode: diff and raw both zeroed
    diff_nb = np.zeros(N, dtype=np.float32)
    raw_nb  = np.zeros(N, dtype=np.float32)
    feats_nb = np.column_stack([cx, cy, cz, diff_nb, raw_nb])
    assert feats_nb[:, 3].sum() == 0.0
    assert feats_nb[:, 4].sum() == 0.0

    # mask-only-diff: raw present, diff zeroed (partial-baseline mode)
    diff_mask = np.zeros(N, dtype=np.float32)
    feats_partial = np.column_stack([cx, cy, cz, diff_mask, raw])
    assert feats_partial[:, 3].sum() == 0.0
    assert feats_partial[:, 4].sum() != 0.0

    # healthy-node noise: only class-0 nodes are perturbed
    label_mock = np.zeros(N, dtype=np.int32)
    label_mock[:N//3] = 1   # first 1/3 are defective
    healthy_mask = (label_mock == 0).astype(np.float32)
    noise_h = np.random.normal(0, 0.03, N).astype(np.float32)
    raw_h   = raw + noise_h * healthy_mask
    # defective nodes should be unchanged
    assert np.allclose(raw_h[:N//3], raw[:N//3]), "defective nodes should not be perturbed"
    # healthy nodes should differ
    assert not np.allclose(raw_h[N//3:], raw[N//3:]), "healthy nodes should be perturbed"

    # baseline noise: diff is shifted by per-node perturbation
    bl_noise    = np.random.normal(0, 0.02, N).astype(np.float32)
    diff_bl     = diff - bl_noise
    assert not np.allclose(diff_bl, diff), "baseline noise should change diff channel"

    # channel dropout: diff is fully zeroed
    diff_dropped = np.zeros(N, dtype=np.float32)
    feats_drop   = np.column_stack([cx, cy, cz, diff_dropped, raw])
    assert feats_drop[:, 3].sum() == 0.0, "diff should be zero after dropout"
    assert feats_drop[:, 4].sum() != 0.0, "raw should still be present after dropout"

    print("[test] PASS — feature shapes and all augmentation modes correct.")

    # Verify in_channels=5 is accepted by T.build_model (if train.py is importable)
    try:
        model = T.build_model(arch="hybridmgn", in_channels=5)
        n_params = sum(p.numel() for p in model.parameters())
        # expect slightly more params than in_channels=4 version
        model4  = T.build_model(arch="hybridmgn", in_channels=4)
        n_params4 = sum(p.numel() for p in model4.parameters())
        assert n_params > n_params4, "5-channel model should have more params than 4-channel"
        print(f"[test] PASS — HybridMGN in_channels=5: {n_params:,} params "
              f"(vs 4-channel: {n_params4:,}, Δ={n_params - n_params4:,})")
    except Exception as e:
        print(f"[test] SKIP model build (Vancouver-only dep): {e}")

    print("[test] ALL PASS")


