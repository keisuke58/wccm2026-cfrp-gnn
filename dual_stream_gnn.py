DIR_DIFF = GD / "GNN_hole_2026/all_sub_hole_defect_zscore"   # diff-norm (existing)
DIR_RAW  = GD / "GNN_hole_2026/all_hole_defect_zscore"        # raw z-score (generated by prepare_plain_zscore.py)
DIR_LBL  = GD / "GNN_hole_2026/all_19class_label"
