N_NODES = 13942


# ─────────────────────────────────────────────────────────────────────────────
# Data loading
# ─────────────────────────────────────────────────────────────────────────────

def _load_coords() -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    x = np.load(DIR_COORD / "normalized_x_2layer.npy")[:N_NODES]
    y = np.load(DIR_COORD / "normalized_y_2layer.npy")[:N_NODES]
    z = np.load(DIR_COORD / "normalized_z_2layer.npy")[:N_NODES]
    return x, y, z


def _load_edges() -> torch.Tensor:
    edges = np.load(DIR_COORD / "hole_edges_2layer_best.npy")
    return torch.tensor(edges, dtype=torch.long)


def build_dual_data(
    split: str,
    no_baseline: bool = False,
    noise_std: float = 0.0,
    noise_healthy_std: float = 0.0,
    baseline_noise_std: float = 0.0,
    diff_channel_dropout: float = 0.0,
) -> List[Data]:
    """
    Load {train, val, test} specimens with 5-channel node features:
        [x, y, z, dspss_diff, dspss_raw]

    Parameters — noise augmentation ("strongest model")
    ----------
    split                 : 'train' | 'val' | 'test'
    no_baseline           : zero both DSPSS channels (baseline-free inference)
    noise_std             : measurement noise on defective specimens (both channels)
    noise_healthy_std     : noise added to raw of healthy specimens (class-0 nodes)
                            → makes Stage-0 robust when the healthy reference is noisy
    baseline_noise_std    : perturb the diff channel by N(0, σ²) PER SPECIMEN
                            → simulates imperfect/noisy 1st-flight baseline
    diff_channel_dropout  : probability [0,1] to zero the diff channel for a specimen
                            → forces model to learn from raw alone (no-baseline robustness)
    """
    diff_dir = DIR_DIFF / split
    raw_dir  = DIR_RAW  / split
    lbl_dir  = DIR_LBL

    if not raw_dir.is_dir():
        raise FileNotFoundError(
            f"Raw z-score data not found at {raw_dir}.\n"
            f"Generate it first:  python data_prep/prepare_plain_zscore.py"
        )

    cx, cy, cz = _load_coords()
    edge_index  = _load_edges()

    coord_block = np.column_stack([cx, cy, cz])   # (N, 3)

    files = sorted(f for f in os.listdir(diff_dir) if f.endswith(".npy"))
    data_list: List[Data] = []
    is_train = (split == "train")

    for fname in files:
        lbl_fname = fname.replace(".npy", "_19label.npy")
        lbl_path  = lbl_dir / lbl_fname
        if not lbl_path.exists():
            continue

        diff_vals = np.load(diff_dir / fname)[:N_NODES].astype(np.float32)
        label     = np.load(lbl_path)[:N_NODES]

        # raw channel — use zero if no_baseline or file missing
        raw_path = raw_dir / fname
        if no_baseline or not raw_path.exists():
            raw_vals  = np.zeros(N_NODES, dtype=np.float32)
            diff_vals = np.zeros(N_NODES, dtype=np.float32)
        else:
            raw_vals = np.load(raw_path)[:N_NODES].astype(np.float32)

        if is_train:
            # 1. Measurement noise on both channels (defective specimens)
            if noise_std > 0.0:
                diff_vals = diff_vals + np.random.normal(0, noise_std, N_NODES).astype(np.float32)
                raw_vals  = raw_vals  + np.random.normal(0, noise_std, N_NODES).astype(np.float32)

            # 2. Healthy-node noise: add extra noise to class-0 nodes in raw
            #    Simulates the case where the "healthy reference" used for Stage-0
            #    fitting is itself noisy — teaches Stage-0 to be noise-robust.
            if noise_healthy_std > 0.0:
                lbl_for_mask = label[:N_NODES].astype(np.int32)
                if lbl_for_mask.ndim == 2:
                    lbl_for_mask = lbl_for_mask.argmax(axis=1)
                healthy_mask = (lbl_for_mask == 0).astype(np.float32)
                hn = np.random.normal(0, noise_healthy_std, N_NODES).astype(np.float32)
                raw_vals = raw_vals + hn * healthy_mask

            # 3. Baseline noise: perturb the diff channel to simulate imperfect baseline
            #    diff_measured = raw - (baseline_true + ε),  ε ~ N(0, σ_bl²)
            if baseline_noise_std > 0.0 and not no_baseline:
                bl_noise  = np.random.normal(0, baseline_noise_std, N_NODES).astype(np.float32)
                diff_vals = diff_vals - bl_noise   # subtract baseline perturbation

            # 4. Channel dropout: randomly zero the diff channel for this specimen
            #    Forces the model to also be capable of prediction from raw alone.
            if diff_channel_dropout > 0.0 and np.random.rand() < diff_channel_dropout:
                diff_vals = np.zeros(N_NODES, dtype=np.float32)

        # node features: [x, y, z, diff, raw]
        feats = np.column_stack([coord_block, diff_vals, raw_vals])  # (N, 5)
        x_t   = torch.tensor(feats, dtype=torch.float)

        # labels
        lbl_t = torch.tensor(label, dtype=torch.float)
        if lbl_t.ndim == 2 and lbl_t.shape[1] > 1:
            y = torch.argmax(lbl_t, dim=1).long()
        else:
            y = lbl_t.long().squeeze()

        d = Data(x=x_t, edge_index=edge_index, y=y)
        d.filename = fname
        data_list.append(d)

    print(f"[dual] split={split}  loaded={len(data_list)}  "
          f"no_baseline={no_baseline}  in_channels=5")
    return data_list


# ─────────────────────────────────────────────────────────────────────────────
# Architecture wrapper  (thin: just overrides in_channels)
# ─────────────────────────────────────────────────────────────────────────────

def build_model(arch: str, device: torch.device) -> torch.nn.Module:
    """
    Reuse existing architectures from train.py with in_channels=5.
    The only change: the first linear layer is wider by one input.
    """
    model = T.build_model(arch=arch, in_channels=5)
    return model.to(device)


# ─────────────────────────────────────────────────────────────────────────────
# Training loop (minimal — delegates metrics to train.py helpers)
# ─────────────────────────────────────────────────────────────────────────────

def train_dual(args: argparse.Namespace) -> None:
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[dual] device={device}  arch={args.arch}")

    train_data = build_dual_data(
        "train",
        noise_std=args.noise_std,
        noise_healthy_std=args.noise_healthy_std,
        baseline_noise_std=args.baseline_noise_std,
        diff_channel_dropout=args.diff_channel_dropout,
    )
    val_data   = build_dual_data("val")

    train_loader = DataLoader(train_data, batch_size=args.batch_size, shuffle=True,  num_workers=4)
    val_loader   = DataLoader(val_data,   batch_size=args.batch_size, shuffle=False, num_workers=4)

    model     = build_model(args.arch, device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)
    criterion = torch.nn.CrossEntropyLoss()

    best_f1   = 0.0
    CK_OUT.mkdir(parents=True, exist_ok=True)
    ckpt_path = CK_OUT / f"{args.arch}_dual_best.pth"

    for epoch in range(1, args.epochs + 1):
        model.train()
        total_loss = 0.0
        for batch in train_loader:
            batch = batch.to(device)
            optimizer.zero_grad()
            out  = model(batch)
            loss = criterion(out, batch.y)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
        scheduler.step()

        if epoch % args.eval_every == 0:
            f1 = _eval_f1(model, val_loader, device)
            print(f"  epoch {epoch:3d}  loss={total_loss/len(train_loader):.4f}  val_macro_F1={f1:.4f}")
            if f1 > best_f1:
                best_f1 = f1
                torch.save(model.state_dict(), ckpt_path)
                print(f"    → saved  {ckpt_path}  (best={best_f1:.4f})")

    print(f"[dual] training done.  best_val_F1={best_f1:.4f}")


def _eval_f1(model, loader, device) -> float:
    from sklearn.metrics import f1_score
    model.eval()
    y_true, y_pred = [], []
    with torch.no_grad():
        for batch in loader:
            batch = batch.to(device)
            pred  = model(batch).argmax(dim=1)
            y_true.extend(batch.y.cpu().numpy())
            y_pred.extend(pred.cpu().numpy())
    return float(f1_score(y_true, y_pred, average="macro", zero_division=0))


def eval_dual(args: argparse.Namespace) -> None:
    device    = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    test_data = build_dual_data("test", no_baseline=args.no_baseline)
    loader    = DataLoader(test_data, batch_size=args.batch_size, shuffle=False, num_workers=4)

    model = build_model(args.arch, device)
    state = torch.load(args.ckpt, map_location=device)
    model.load_state_dict(state)
    model.eval()

    f1 = _eval_f1(model, loader, device)
    mode = "no-baseline (raw only)" if args.no_baseline else "full dual (raw+diff)"
    print(f"[dual] eval  mode={mode}  macro_F1={f1:.4f}")

    # comparison baseline
    print("[dual] reference F1s from RESULTS.md:")
    print("  raw DSPSS (current WCCMtalk): 0.61")
    print("  diff-norm HybridMGN (standalone): 0.792")
    print("  diff-norm + Stage-0: 0.803")
    print(f"  THIS RUN ({mode}): {f1:.4f}")


