"""
dual_stream_gnn.py — Dual-stream (raw + diff-norm) GNN experiment.

Idea B: feed both raw DSPSS and difference-normalised DSPSS as separate node
feature channels so the GNN can learn their complementarity.

Node features: [x, y, z, dspss_diff, dspss_raw]  (in_channels=5)

Design rationale
----------------
- diff-norm removes hole-edge background → clean defect signal, depth discrimination
- raw carries absolute stress level → hole-edge geometry cue, no baseline needed
- At inference without baseline: zero the diff channel (→ model falls back to raw)
- No change to any existing architecture: just pass in_channels=5

Prerequisites on Vancouver
--------------------------
1. Generate plain (raw) z-score data:
       python data_prep/prepare_plain_zscore.py
   This creates:  GNN/GNN_hole_2026/all_hole_defect_zscore/{train,val,test}/

2. Run this script:
       python dual_stream_gnn.py --train
       python dual_stream_gnn.py --eval --no_baseline   # simulate baseline-free

Usage
-----
    python dual_stream_gnn.py --train --arch hybridmgn
    python dual_stream_gnn.py --eval  --ckpt <path>
    python dual_stream_gnn.py --eval  --ckpt <path> --no_baseline
    python dual_stream_gnn.py --test   # unit tests

Author: Nishioka (2026-06)
"""
