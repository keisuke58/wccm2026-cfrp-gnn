"""electrothermal_dataset.py — publication-grade DATASET generator for research
theme G (device self-heating = electro-thermal coupling), built on the weak-form
FE model of ⑯ `electrothermal_selfheating.py`.

Motivation (see research/LITREVIEW_G_electrothermal.md §5-6): the self-heating
literature trains ML surrogates on *proprietary* commercial-TCAD (Sentaurus) data;
there is no open benchmark dataset of self-consistent electro-thermal responses.
This script generates one — a labeled DESIGN-SPACE dataset spanning the physically
meaningful axes, so a downstream surrogate has something reproducible to learn from
and so the NDR / thermal-runaway phase boundary is itself a datum.

Physics (identical to ⑯, reused via import, not re-implemented):
    -kappa T'' + h (T - T0) = J^2 / sigma(T),   sigma(T) = exp(EA (1/T0 - 1/T)),
weak-form P1 FE, damped Newton, current continuation. Terminal voltage
V(J) = J * integral dx / sigma(T). Temperature-activated conduction + Joule heat
give an S-shaped I-V with negative differential resistance (NDR); a strong-enough
feedback with a weak sink has no steady solution = THERMAL RUNAWAY.

Swept axes (each with a device/process meaning):
  * EA    — activation of conduction (material / bandgap proxy; larger = stronger
            electro-thermal feedback),
  * HSINK — distributed substrate coupling (packaging / thermal design; ~ 1/Rth,
            larger = better heat removal),
  * KAPPA — lateral heat conduction (geometry / spreading).
Each (EA, HSINK, KAPPA) point gets a full current-continuation I-V sweep, a
temperature field, warm-vs-cold Newton iteration counts, and a REGIME label:
  monotone  (V rises with J throughout — voltage-stable, no NDR),
  NDR-fold  (V peaks then folds back = S-shape; the fold branch is voltage-control
             *unstable* — under voltage drive it snaps / thermally runs away — so
             current continuation is what makes this branch tractable at all).
Note: because sigma RISES with T here, the Joule source J^2/sigma *falls* as T
rises, so current control is self-stabilizing — genuine thermal runaway is a
VOLTAGE-control phenomenon and does not occur under current continuation. That is
exactly the point: continuation trades the voltage-unstable fold for a stable
current-parametrized branch. The NDR-fold label therefore marks the design points
a naive voltage-driven solver would fail on.

Outputs:
  electrothermal_dataset.csv  — one row per (combo, current step)
  electrothermal_dataset.npz  — structured arrays (grids, I-V + Tmax curves,
                                regime labels, final T(x), iteration counts, meta)
  electrothermal_dataset.png  — I-V family, (EA,HSINK) regime phase map,
                                warm-start savings, peak-V trend

Honest scope: reduced electro-thermal model (temperature-activated Ohmic
conduction), non-dimensional units, 1D. This is the *dataset* step of theme G;
the physics deepening (non-isothermal 2-carrier drift-diffusion = couple ⑧⑨ with
this heat equation, and 2D geometry) is the documented next axis. No ML here — the
dataset is generated by physics; ML would consume it downstream.

Run:  python3 electrothermal_dataset.py            (writes the three files above)
      python3 electrothermal_dataset.py --help
"""
from __future__ import annotations

import argparse
import csv

import numpy as np

from electrothermal_selfheating import assemble, solve_T, voltage

SEED = 20260725
STALL_TFACTOR = 15.0         # Tmax/T0 above this (or Newton stall) = truncate sweep
MONO_TOL = 1e-4              # V fold smaller than this (relative) counts as monotone

REGIME_NAMES = ("monotone", "NDR-fold")


def sweep_one(ea, hsink, kappa, Js, n, T0=1.0):
    """One (EA, HSINK, KAPPA) design point: current-continuation I-V sweep (warm),
    plus a cold pass for the iteration comparison. Returns padded per-step arrays
    (NaN past a runaway) and a scalar summary dict."""
    x, K, ml = assemble(n)
    Kk = (kappa * K).tocsc()
    nstep = len(Js)
    V = np.full(nstep, np.nan); Tmax = np.full(nstep, np.nan)
    conv = np.zeros(nstep, dtype=bool)
    warm_it = np.zeros(nstep, dtype=int)

    Tw = np.full(n, T0); T_last = Tw.copy()
    stall_at = np.nan
    for k, J in enumerate(Js):
        Ts, it, _ = solve_T(J, Kk, ml, Tw, ea=ea, hsink=hsink, t0=T0)
        stalled = (it >= 79) or (not np.all(np.isfinite(Ts))) or (Ts.max() / T0 > STALL_TFACTOR)
        if stalled:
            stall_at = J
            break
        Tw = Ts; T_last = Ts.copy()
        V[k] = voltage(J, Ts, x, ea=ea, t0=T0); Tmax[k] = Ts.max()
        conv[k] = True; warm_it[k] = it

    # cold pass (each J from ambient) over the converged steps only
    cold_it = np.zeros(nstep, dtype=int)
    for k, J in enumerate(Js):
        if not conv[k]:
            break
        _, it, _ = solve_T(J, Kk, ml, np.full(n, T0), ea=ea, hsink=hsink, t0=T0)
        cold_it[k] = it

    nconv = int(conv.sum())
    Vc = V[:nconv]
    if nconv >= 2:
        kpk = int(np.argmax(Vc))
        folds = kpk < nconv - 1 and (Vc[kpk] - Vc[-1]) > MONO_TOL * max(Vc[kpk], 1e-12)
        regime = 1 if folds else 0                   # 1 = NDR-fold (voltage-unstable)
    else:
        kpk = -1; regime = 0

    summary = dict(
        EA=ea, HSINK=hsink, KAPPA=kappa, regime=regime, nconv=nconv,
        J_peak=(Js[kpk] if kpk >= 0 else np.nan),
        V_peak=(Vc[kpk] if kpk >= 0 else np.nan),
        J_stall=stall_at,
        Tmax_end=(Tmax[nconv - 1] if nconv else np.nan),
        cold_iters=int(cold_it[:nconv].sum()), warm_iters=int(warm_it[:nconv].sum()),
    )
    return V, Tmax, conv, warm_it, cold_it, T_last, summary


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=81, help="FE nodes")
    ap.add_argument("--nstep", type=int, default=60, help="current-continuation steps")
    ap.add_argument("--jmax", type=float, default=7.0, help="max current density")
    ap.add_argument("--nea", type=int, default=8, help="# activation-energy (EA) samples")
    ap.add_argument("--out", type=str, default="electrothermal_dataset.png")
    ap.add_argument("--data", type=str, default="electrothermal_dataset",
                    help="dataset basename (.csv per-step rows + .npz structured arrays)")
    args = ap.parse_args()

    EA_grid = np.linspace(3.0, 20.0, args.nea)          # material / feedback strength
    HSINK_grid = np.array([0.5, 1.0, 2.0, 4.0, 8.0])    # packaging heat removal (~1/Rth)
    KAPPA_grid = np.array([0.02, 0.08])                 # geometry / lateral spreading
    Js = np.linspace(args.jmax / args.nstep, args.jmax, args.nstep)

    combos = [(ea, hs, ka) for ka in KAPPA_grid for hs in HSINK_grid for ea in EA_grid]
    nc = len(combos)
    V_all = np.full((nc, args.nstep), np.nan)
    Tmax_all = np.full((nc, args.nstep), np.nan)
    conv_all = np.zeros((nc, args.nstep), dtype=bool)
    warm_all = np.zeros((nc, args.nstep), dtype=int)
    cold_all = np.zeros((nc, args.nstep), dtype=int)
    Tfinal_all = np.full((nc, args.n), np.nan)
    meta = np.zeros((nc, 3))                             # EA, HSINK, KAPPA
    regime = np.zeros(nc, dtype=int)
    Jpk = np.full(nc, np.nan); Vpk = np.full(nc, np.nan); Jst = np.full(nc, np.nan)
    ctot = np.zeros(nc, dtype=int); wtot = np.zeros(nc, dtype=int)

    for i, (ea, hs, ka) in enumerate(combos):
        V, Tmax, conv, wit, cit, Tl, s = sweep_one(ea, hs, ka, Js, args.n)
        V_all[i] = V; Tmax_all[i] = Tmax; conv_all[i] = conv
        warm_all[i] = wit; cold_all[i] = cit; Tfinal_all[i] = Tl
        meta[i] = (ea, hs, ka); regime[i] = s["regime"]
        Jpk[i] = s["J_peak"]; Vpk[i] = s["V_peak"]; Jst[i] = s["J_stall"]
        ctot[i] = s["cold_iters"]; wtot[i] = s["warm_iters"]

    n_mono = int(np.sum(regime == 0)); n_ndr = int(np.sum(regime == 1))
    tc, tw = int(ctot.sum()), int(wtot.sum())
    print(f"\nelectro-thermal design-space dataset: {nc} points "
          f"({args.nea} EA x {len(HSINK_grid)} HSINK x {len(KAPPA_grid)} KAPPA), "
          f"{args.nstep} current steps each")
    print(f"  regimes: monotone {n_mono}  NDR-fold {n_ndr}  "
          f"(NDR-fold = voltage-control-unstable; current control stays stable)")
    print(f"  self-consistent FE solves: ~{2 * int(conv_all.sum())} "
          f"(warm continuation + cold reference)")
    print(f"  Newton iters over all points  cold {tc}  warm {tw}  "
          f"({100 * (tc - tw) / max(tc, 1):.0f}% fewer via continuation warm-start)")

    if args.data:
        np.savez(
            args.data + ".npz", EA_grid=EA_grid, HSINK_grid=HSINK_grid,
            KAPPA_grid=KAPPA_grid, Js=Js, combos=meta, regime=regime,
            regime_names=np.array(REGIME_NAMES), V=V_all, Tmax=Tmax_all,
            converged=conv_all, warm_iters=warm_all, cold_iters=cold_all,
            T_final=Tfinal_all, J_peak=Jpk, V_peak=Vpk, J_stall=Jst,
            cold_iters_total=ctot, warm_iters_total=wtot,
            params=dict(n=args.n, nstep=args.nstep, jmax=args.jmax,
                        STALL_TFACTOR=STALL_TFACTOR))
        with open(args.data + ".csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["combo", "EA", "HSINK", "KAPPA", "regime",
                        "step", "J", "V", "Tmax", "converged"])
            for i, (ea, hs, ka) in enumerate(combos):
                for k in range(args.nstep):
                    w.writerow([i, f"{ea:.4g}", f"{hs:.4g}", f"{ka:.4g}",
                                REGIME_NAMES[regime[i]], k, f"{Js[k]:.6g}",
                                "" if np.isnan(V_all[i, k]) else f"{V_all[i, k]:.6g}",
                                "" if np.isnan(Tmax_all[i, k]) else f"{Tmax_all[i, k]:.6g}",
                                int(conv_all[i, k])])
        print(f"wrote dataset {args.data}.csv ({nc * args.nstep} rows) and "
              f"{args.data}.npz")

    _plot(args.out, EA_grid, HSINK_grid, KAPPA_grid, Js, combos, meta, regime,
          V_all, Vpk, ctot, wtot, tc, tw)
    print(f"wrote {args.out}")


def _plot(out, EA_grid, HSINK_grid, KAPPA_grid, Js, combos, meta, regime,
          V_all, Vpk, ctot, wtot, tc, tw):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(2, 2, figsize=(13, 10))
    rc = {0: "#2ca02c", 1: "#1f77b4", 2: "#d62728"}

    # I-V family (fixed HSINK=1.0, KAPPA=0.02) coloured by EA
    ka0, hs0 = KAPPA_grid[0], 1.0
    cmap = plt.cm.viridis
    for i, (ea, hs, ka) in enumerate(combos):
        if abs(hs - hs0) < 1e-9 and abs(ka - ka0) < 1e-9:
            c = cmap((ea - EA_grid[0]) / (EA_grid[-1] - EA_grid[0] + 1e-9))
            m = np.isfinite(V_all[i])
            ax[0, 0].plot(V_all[i][m], Js[m], "-", color=c, label=f"EA={ea:.0f}")
    ax[0, 0].set_xlabel("terminal voltage V"); ax[0, 0].set_ylabel("current density J")
    ax[0, 0].set_title(f"I-V family vs activation EA (HSINK={hs0}, KAPPA={ka0})\n"
                       "stronger feedback → earlier fold (NDR)")
    ax[0, 0].legend(fontsize=7, ncol=2); ax[0, 0].grid(True, alpha=0.3)

    # regime phase map in (EA, HSINK) for KAPPA=0.02
    for i, (ea, hs, ka) in enumerate(combos):
        if abs(ka - KAPPA_grid[0]) < 1e-9:
            ax[0, 1].scatter(ea, hs, s=130, color=rc[regime[i]],
                             edgecolor="k", linewidth=0.5, zorder=3)
    for r, name in enumerate(REGIME_NAMES):
        ax[0, 1].scatter([], [], color=rc[r], edgecolor="k", label=name)
    ax[0, 1].set_xlabel("activation EA (material / feedback)")
    ax[0, 1].set_ylabel("substrate coupling HSINK (~1/Rth)")
    ax[0, 1].set_title(f"self-heating regime phase map (KAPPA={KAPPA_grid[0]})\n"
                       "monotone (V-stable) → NDR-fold (V-control unstable)")
    ax[0, 1].legend(fontsize=8); ax[0, 1].grid(True, alpha=0.3)

    # warm vs cold total Newton iterations per design point
    order = np.argsort(ctot)
    xs = np.arange(len(combos))
    ax[1, 0].plot(xs, ctot[order], "-o", ms=3, color="#d62728", label="cold (ambient)")
    ax[1, 0].plot(xs, wtot[order], "-o", ms=3, color="#1f77b4", label="warm (continuation)")
    ax[1, 0].set_xlabel("design point (sorted by cold cost)")
    ax[1, 0].set_ylabel("total Newton iterations")
    ax[1, 0].set_title(f"continuation warm-start over the whole sweep\n"
                       f"cold {tc} → warm {tw} ({100*(tc-tw)/max(tc,1):.0f}% fewer)")
    ax[1, 0].legend(); ax[1, 0].grid(True, alpha=0.3)

    # peak terminal voltage vs EA (NDR onset trend), per HSINK
    for hs in HSINK_grid:
        eas, vps = [], []
        for i, (ea, h, ka) in enumerate(combos):
            if abs(h - hs) < 1e-9 and abs(ka - KAPPA_grid[0]) < 1e-9 and np.isfinite(Vpk[i]):
                eas.append(ea); vps.append(Vpk[i])
        if eas:
            ax[1, 1].plot(eas, vps, "-o", ms=4, label=f"HSINK={hs}")
    ax[1, 1].set_xlabel("activation EA"); ax[1, 1].set_ylabel("peak terminal voltage V*")
    ax[1, 1].set_title("NDR onset: peak voltage before fold\n(higher sink → holds off the fold)")
    ax[1, 1].legend(fontsize=8); ax[1, 1].grid(True, alpha=0.3)

    fig.suptitle("Electro-thermal self-heating DESIGN-SPACE dataset (theme G): "
                 "material × packaging × geometry, labeled monotone / NDR-fold",
                 fontsize=12)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(out, dpi=130)


if __name__ == "__main__":
    main()
